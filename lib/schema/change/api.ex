defmodule BoxTurtle.Schema.Change.API do
  @moduledoc """
  Write operations generated by `use BoxTurtle.Schema.Change`: create, update and delete.

  The counterpart to `BoxTurtle.Schema.Query.API`, with the idea that nothing outside a Query or Change module
  touches the Repo. Plain functions return `{:ok, struct}` / `{:error, changeset}` like `Ecto.Repo`; `!`
  functions return the struct or raise.
  """

  @type schema :: Ecto.Schema.t()
  @type attrs :: map() | schema()
  @type key :: term()

  @doc "Inserts a changeset, or a changeset built from a map (or struct) of attributes."
  @callback create(attrs() | Ecto.Changeset.t()) :: {:ok, schema()} | {:error, Ecto.Changeset.t()}
  @callback create!(attrs() | Ecto.Changeset.t()) :: schema()

  @doc "Updates a changeset, or a struct with a map of changes."
  @callback update(Ecto.Changeset.t()) :: {:ok, schema()} | {:error, Ecto.Changeset.t()}
  @callback update(schema(), map()) :: {:ok, schema()} | {:error, Ecto.Changeset.t()}
  @callback update!(Ecto.Changeset.t()) :: schema()
  @callback update!(schema(), map()) :: schema()

  @doc "Deletes a struct, a changeset, or the row with the given primary key (`{:error, :not_found}` if absent)."
  @callback delete(key() | schema() | Ecto.Changeset.t()) ::
              {:ok, schema()} | {:error, Ecto.Changeset.t() | :not_found}
  @callback delete!(key() | schema() | Ecto.Changeset.t()) :: schema()
end
