defmodule BoxTurtle.Schema.Query.API do
  @moduledoc """
  Read operations generated by `use BoxTurtle.Schema.Query`.

  Functions come in pairs: the plain form returns `{:ok, result}` / `{:error, reason}`, the `!` form returns the
  result directly (`nil` when `get!/2` finds nothing).

  ## Call-time options

    * `:filters` - keyword list of filters, see `BoxTurtle.Schema.Filters`
    * `:sort` - sort specification, see `BoxTurtle.Schema.Sort`
    * `:page` - page number or `[number: n, size: s]`, see `BoxTurtle.Schema.Pagination`
    * `:preloads` - associations to preload, nested to any depth (`[:author, comments: :user]`). They are
      `LEFT JOIN`ed and loaded in the same query, see `BoxTurtle.Schema.Query.Helpers.preloads/3`.
      Ignored by aggregates
    * `:distinct` - columns for `DISTINCT ON` (PostgreSQL only); a count uses the first one as
      `COUNT(DISTINCT column)`, which works on every database
    * `:group_by` - columns to group by; `count` then returns a list of maps
    * `:aggregate` - `:count` (used internally by `count/1`)
    * `:ignore_defaults` - when true, the module's default sort, preloads and distinct are not applied
    * `:query_opts` - options passed to `c:Ecto.Repo.all/2` by `list/1`

  Any `use`-time setting (`:repo`, `:schema`, `:default_sort`, ...) can also be overridden per call; see
  `BoxTurtle.Schema.Query.Options.API`.

  ## Extension functions

  The `*_by` callbacks are optional. They are generated with `BoxTurtle.Schema.Query.extend/2` and
  `BoxTurtle.Schema.Query.delegate/1`, which scope a query by a pattern (e.g. "all posts of this `%Author{}`").
  """

  @type schema :: Ecto.Schema.t()
  @type opts :: keyword()

  @doc "Counts rows, or rows per group when `:group_by` is given."
  @callback count() :: {:ok, integer() | [map()]}
  @callback count(opts()) :: {:ok, integer() | [map()]}
  @callback count!() :: integer() | [map()]
  @callback count!(opts()) :: integer() | [map()]

  @doc "Fetches a row by primary key (or by a map of key columns). `{:error, :not_found}` when absent."
  @callback get(key :: term()) :: {:ok, schema()} | {:error, :not_found}
  @callback get(key :: term(), opts()) :: {:ok, schema()} | {:error, :not_found}
  @callback get!(key :: term()) :: schema() | nil
  @callback get!(key :: term(), opts()) :: schema() | nil

  @doc "Lists rows."
  @callback list() :: {:ok, [schema()]}
  @callback list(opts()) :: {:ok, [schema()]}
  @callback list!() :: [schema()]
  @callback list!(opts()) :: [schema()]

  @doc "Applies the options (sort, filters, paging, preloads or aggregation) to an existing queryable."
  @callback pipe_query!(Ecto.Queryable.t()) :: Ecto.Queryable.t()
  @callback pipe_query!(Ecto.Queryable.t(), opts()) :: Ecto.Queryable.t()

  @doc "Builds a query on the schema from the options, without running it."
  @callback query!() :: Ecto.Queryable.t()
  @callback query!(opts()) :: Ecto.Queryable.t()

  @doc "Counts rows scoped by a pattern. A `nil` pattern counts everything."
  @callback count_by(pattern :: term()) :: {:ok, integer() | [map()]} | {:error, term()}
  @callback count_by(pattern :: term(), opts()) :: {:ok, integer() | [map()]} | {:error, term()}
  @callback count_by!(pattern :: term()) :: integer() | [map()]
  @callback count_by!(pattern :: term(), opts()) :: integer() | [map()]

  @doc "Fetches the row identified by a pattern."
  @callback get_by(pattern :: term()) :: {:ok, schema()} | {:error, term()}
  @callback get_by(pattern :: term(), opts()) :: {:ok, schema()} | {:error, term()}
  @callback get_by!(pattern :: term()) :: schema() | nil
  @callback get_by!(pattern :: term(), opts()) :: schema() | nil

  @doc "Lists rows scoped by a pattern. A `nil` pattern lists everything."
  @callback list_by(pattern :: term()) :: {:ok, [schema()]} | {:error, term()}
  @callback list_by(pattern :: term(), opts()) :: {:ok, [schema()]} | {:error, term()}
  @callback list_by!(pattern :: term()) :: [schema()]
  @callback list_by!(pattern :: term(), opts()) :: [schema()]

  @doc "Builds a query scoped by a pattern."
  @callback query_by!(pattern :: term()) :: Ecto.Queryable.t()
  @callback query_by!(pattern :: term(), opts()) :: Ecto.Queryable.t()

  @optional_callbacks count_by: 1,
                      count_by: 2,
                      count_by!: 1,
                      count_by!: 2,
                      get_by: 1,
                      get_by: 2,
                      get_by!: 1,
                      get_by!: 2,
                      list_by: 1,
                      list_by: 2,
                      list_by!: 1,
                      list_by!: 2,
                      query_by!: 1,
                      query_by!: 2
end
